#!/usr/bin/env bash
# Drive the full Text2KGBench (Wikidata-TekGen) benchmark for the WUKONG engine.
#
# Runs the engine over one workspace per ontology, then converts and evaluates
# every ontology in a single pass. Extraction is sequential so the engine's own
# max_concurrency stays the only source of parallel API calls.
#
# Usage (from the repository root):
#     paper/benchmark/run_benchmark.sh [ontology ...]
#
# With no arguments every ontology that has no staging database yet is run;
# already-extracted ontologies are skipped so the script is resumable.

set -euo pipefail

BENCHMARK=${BENCHMARK:-../benchmarks/Text2KGBench}
ROOT=paper/benchmark
WORKSPACES=$ROOT/workspaces
DATA=$ROOT/data
# PREFIX/RESULTS select an arm: the primary run, or an ablation generated by
# text2kg_setup.py with a different compilation flag and workspace prefix.
PREFIX=${PREFIX:-tekgen_}
RESULTS=${RESULTS:-$ROOT/results}
LOGS=$RESULTS/logs
EVAL_PYTHON=${EVAL_PYTHON:-$PWD/$ROOT/.venv-eval/bin/python}

ALL_ONTOLOGIES=(1_movie 2_music 3_sport 4_book 5_military 6_computer 7_space 8_politics 9_nature 10_culture)
ONTOLOGIES=("${@:-}")
[[ -z ${ONTOLOGIES[0]:-} ]] && ONTOLOGIES=("${ALL_ONTOLOGIES[@]}")

mkdir -p "$LOGS"

for onto in "${ONTOLOGIES[@]}"; do
    workspace=$WORKSPACES/$PREFIX$onto
    # Resume on the final checkpoint rather than on the database file: an
    # interrupted run leaves a staging database behind, and skipping on mere
    # existence would silently accept a half-extracted ontology.
    if [[ -f $workspace/staging/extraction.db ]] && python3 - "$workspace/staging/extraction.db" <<'PY'
import sqlite3, sys
connection = sqlite3.connect(f'file:{sys.argv[1]}?mode=ro', uri=True)
done = connection.execute(
    "SELECT COUNT(*) FROM pipeline_checkpoints"
    " WHERE checkpoint_name = 'KNOWLEDGE_EXPORTED' AND checkpoint_status = 'COMPLETED'",
).fetchone()[0]
sys.exit(0 if done else 1)
PY
    then
        echo "== $onto: already extracted, skipping"
        continue
    fi
    echo "== $onto: extracting ($(date -Is))"
    wukong run "$workspace" "$DATA/$onto" --config config/default.toml -v \
        >"$LOGS/$onto.log" 2>&1
    echo "== $onto: done ($(date -Is))"
done

# Conversion and evaluation cover exactly the ontologies this invocation ran, so
# an arm restricted to a subset does not fail on the workspaces it never built
SELECTED=()
for onto in "${ONTOLOGIES[@]}"; do SELECTED+=(--onto "$onto"); done

echo
echo "== Converting to benchmark system output"
python3 $ROOT/text2kg_export.py --benchmark "$BENCHMARK" --out "$RESULTS/wukong" --prefix "$PREFIX" \
    "${SELECTED[@]}"

echo
echo "== Running the official Text2KGBench evaluator"
python3 $ROOT/text2kg_eval.py --benchmark "$BENCHMARK" \
    --responses "$RESULTS/wukong" --out "$RESULTS/eval" --python "$EVAL_PYTHON" "${SELECTED[@]}"

# The metrics shipped with the benchmark mix the main test split with a separate
# "unseen sentences" split, and the Alpaca file carries no global row, so both
# baselines are re-scored here from their published outputs under this harness.
echo
echo "== Re-scoring the published baselines"
BASELINES=$BENCHMARK/data/wikidata_tekgen/baselines
python3 $ROOT/text2kg_eval.py --benchmark "$BENCHMARK" \
    --responses "$BASELINES/Vicuna-13B/llm_responses" \
    --sys-pattern 'ont_$$onto$$_llm_responses.jsonl' \
    --out "$RESULTS/baselines/Vicuna-13B" --python "$EVAL_PYTHON" >/dev/null
python3 $ROOT/text2kg_eval.py --benchmark "$BENCHMARK" \
    --responses "$BASELINES/Alpaca-LoRA-13B/llm_responses" \
    --sys-pattern 'ont_$$onto$$_lora-13b_responses_v2.jsonl' \
    --out "$RESULTS/baselines/Alpaca-LoRA-13B" --python "$EVAL_PYTHON" >/dev/null

echo
echo "== Summary"
python3 $ROOT/text2kg_report.py --results "$RESULTS" --workspace-root "$WORKSPACES" \
    --prefix "$PREFIX" --benchmark "$BENCHMARK"
